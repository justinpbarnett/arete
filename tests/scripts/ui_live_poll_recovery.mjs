const flush = async () => { for (let i = 0; i < 40; i++) await Promise.resolve(); };
async function advance(ms) {
  const end = now + ms;
  for (;;) {
    await flush();
    const due = [...timers].filter(([, timer]) => timer.at <= end).sort((a, b) => a[1].at - b[1].at)[0];
    if (!due) break;
    now = Math.max(now, due[1].at);
    timers.delete(due[0]);
    due[1].fn();
  }
  now = end;
  await flush();
}
